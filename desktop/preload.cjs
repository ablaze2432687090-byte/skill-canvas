const { contextBridge, ipcRenderer } = require('electron');
const invoke = (name, ...args) => ipcRenderer.invoke(`desktop:${name}`, ...args);
contextBridge.exposeInMainWorld('skillCanvasDesktop', {
  connection: () => invoke('connection'),
  info: () => invoke('info'),
  setTheme: theme => invoke('set-theme',theme),
  setLanguage: language => invoke('set-language',language),
  translations: () => invoke('translations'),
  environment: () => invoke('environment'),
  completeSetup: () => invoke('complete-setup'),
  saveSetupStep: step => invoke('setup-progress',step),
  setupStep: () => invoke('setup-progress-state'),
  diagnostics: () => invoke('diagnostics'),
  exportDiagnostics:()=>invoke('export-diagnostics'),
  copyDiagnostics: () => invoke('copy-diagnostics'),
  openReleases: () => invoke('open-releases'),
  migrateDataLocation: () => invoke('migrate-data-location'),
  reconnectDataLocation: () => invoke('reconnect-data-location'),
  onMigration: callback => {const listener=(_event,value)=>callback(value);ipcRenderer.on('desktop:migration-progress',listener);return()=>ipcRenderer.removeListener('desktop:migration-progress',listener);},
  chooseCodex: reset => invoke('pick-codex', reset),
  officialSetup: () => invoke('official-setup'),
  backupData: token => invoke('backup-data',token),
  reportBackupFailure:()=>invoke('backup-schedule-failed'),
  backupSchedule:()=>invoke('backup-schedule'),
  saveBackupSchedule:value=>invoke('save-backup-schedule',value),
  runScheduledBackup:token=>invoke('run-scheduled-backup',token),
  restoreData: token => invoke('restore-data',token),
  beginDraftBackup: (state,assets) => invoke('draft-backup-begin',state,assets),
  addDraftBackupAsset: (token,asset) => invoke('draft-backup-asset',token,asset),
  finishDraftBackup: token => invoke('draft-backup-finish',token),
  cancelDraftBackup: token => invoke('draft-backup-cancel',token),
  restoreState: () => invoke('restore-state'),
  startImageProbe: () => invoke('probe-start'),
  imageProbeState: () => invoke('probe-state'),
  updateState: () => invoke('update-state'),
  checkUpdates: () => invoke('update-check'),
  downloadUpdate: () => invoke('update-download'),
  installUpdate: () => invoke('update-install'),
  onUpdate: callback => { const listener=(_event,value)=>callback(value);ipcRenderer.on('desktop:update',listener);return()=>ipcRenderer.removeListener('desktop:update',listener); },
  restartBridge: () => invoke('restart'),
  migrate: mode => invoke('migrate', mode),
  chooseExportDirectory: reset => invoke('export-directory', reset),
  savePng: (taskId, outputId, suggestedName) => invoke('save-png', taskId, outputId, suggestedName),
  exportProjects: ids => invoke('export-projects',ids),
  onExport: callback => {const listener=(_event,value)=>callback(value);ipcRenderer.on('desktop:export-progress',listener);return()=>ipcRenderer.removeListener('desktop:export-progress',listener);},
  reveal: (kind, id, outputId) => invoke('reveal', kind, id, outputId),
  pickSkillDirectory: () => invoke('pick-skill-directory'),
  onService: callback => { const listener = (_event, value) => callback(value); ipcRenderer.on('desktop:service', listener); return () => ipcRenderer.removeListener('desktop:service', listener); },
  onBeforeClose: callback => { const listener = async (_event, id) => { try { await callback(); ipcRenderer.send('desktop:flushed', { id, ok: true }); } catch { ipcRenderer.send('desktop:flushed', { id, ok: false }); } }; ipcRenderer.on('desktop:flush', listener); return () => ipcRenderer.removeListener('desktop:flush', listener); },
});
